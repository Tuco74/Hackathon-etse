def _rows(spec: str):
    return spec.split("|")


def _glyph(char: str):
    """Return (pixels, advance) in a CELL_H tall cell."""
    if char in UPPER:
        rows = _rows(UPPER[char])
        pixels = [(x, y + 3) for y, row in enumerate(rows) for x, ch in enumerate(row) if ch == "#"]
        return pixels, (4 if char == " " else 6)
    if char in LOWER:
        rows = _rows(LOWER[char])
        pixels = [(x, y + 3) for y, row in enumerate(rows) for x, ch in enumerate(row) if ch == "#"]
        return pixels, 6
    if char in ACCENTS:
        base, mark = ACCENTS[char]
        base_pixels, advance = _glyph(base)
        if base in ("i", "j"):
            base_pixels = [(x, y) for x, y in base_pixels if not (x == 2 and y == 3)]
        dy = 0 if base.isupper() else 2
        pixels = base_pixels + [(x + 1, y + dy) for x, y in mark]
        return pixels, advance
    return [], 6


def _charset():
    chars = list(UPPER) + list(LOWER) + list(ACCENTS)
    return sorted({c for c in chars})


def build():
    chars = _charset()
    rows = (len(chars) + COLS - 1) // COLS
    atlas = Image.new("RGBA", (COLS * CELL_W, rows * CELL_H), (0, 0, 0, 0))
    px = atlas.load()
    white = rgb("white")
    entries = []
    for i, ch in enumerate(chars):
        cx, cy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
        pixels, advance = _glyph(ch)
        for x, y in pixels:
            if 0 <= x < CELL_W and 0 <= y < CELL_H:
                px[cx + x, cy + y] = (*white, 255)
        entries.append({
            "id": ord(ch), "char": ch, "x": cx, "y": cy,
            "width": CELL_W, "height": CELL_H, "xoffset": 0, "yoffset": 0,
            "xadvance": advance, "page": 0, "chnl": 15,
        })
    font = {
        "info": {"face": "TrasteroPixel", "size": CELL_H, "bold": 0, "italic": 0,
                 "charset": "", "unicode": 1, "stretchH": 100, "smooth": 0,
                 "aa": 1, "padding": [0, 0, 0, 0], "spacing": [0, 0]},
        "common": {"lineHeight": CELL_H, "base": 12, "scaleW": atlas.width,
                   "scaleH": atlas.height, "pages": 1, "packed": 0,
                   "alphaChnl": 0, "redChnl": 0, "greenChnl": 0, "blueChnl": 0},
        "pages": ["font.png"],
        "chars": entries,
        "kernings": [],
    }
    preview = _preview(chars)
    xml = _xml(font)
    return atlas, font, preview, xml


def _xml(font: dict) -> str:
    """BMFont XML (Phaser's load.bitmapFont only understands XML)."""
    common = font["common"]
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<font>",
        f'  <info face="{font["info"]["face"]}" size="{common["lineHeight"]}" bold="0" italic="0" '
        f'charset="" unicode="1" stretchH="100" smooth="0" aa="1" padding="0,0,0,0" spacing="0,0"/>',
        f'  <common lineHeight="{common["lineHeight"]}" base="{common["base"]}" scaleW="{common["scaleW"]}" '
        f'scaleH="{common["scaleH"]}" pages="{common["pages"]}" packed="0"/>',
        '  <pages>',
        '    <page id="0" file="font.png"/>',
        '  </pages>',
        f'  <chars count="{len(font["chars"])}">',
    ]
    for char in font["chars"]:
        lines.append(
            f'    <char id="{char["id"]}" x="{char["x"]}" y="{char["y"]}" width="{char["width"]}" '
            f'height="{char["height"]}" xoffset="{char["xoffset"]}" yoffset="{char["yoffset"]}" '
            f'xadvance="{char["xadvance"]}" page="0" chnl="15"/>'
        )
    lines += ["  </chars>", "</font>", ""]
    return "\n".join(lines)


def _preview(chars):
    lines = [
        "\u00a1Subasta! \u00bfTrastero n\u00ba 5? Ping\u00fcino",
        "\u00c1rbol a\u00f1ejo, 1.000 \u20ac - puja m\u00ednima",
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ",
        "abcdefghijklmnopqrstuvwxyz 0123456789",
    ]
    scale = 3
    width = max(len(line) for line in lines) * CELL_W * scale + 12
    height = len(lines) * CELL_H * scale + 12
    img = Image.new("RGBA", (width, height), (20, 17, 29, 255))
    px = img.load()
    for row, line in enumerate(lines):
        for col, ch in enumerate(line):
            pixels, _ = _glyph(ch)
            for x, y in pixels:
                for sy in range(scale):
                    for sx in range(scale):
                        py = 6 + row * CELL_H * scale + y * scale + sy
                        px_x = 6 + col * CELL_W * scale + x * scale + sx
                        if 0 <= px_x < width and 0 <= py < height:
                            px[px_x, py] = (*rgb("white"), 255)
    return img
